"""服装阶段名归一化（N1）——把语义同一、字面不同的造型名合并。

## 为什么需要

实测「十八年前」陆明 43 个造型阶段 → 38 个不同名字，其中「白大褂」类
有 17 种不同写法：
    医生白大褂 / 笔挺白大褂 / 医师白大褂 / 医生白大褂工作服 / 标准医师白大褂造型
    医生白大褂正装 / 白大褂医师正装 / 沉稳白大褂造型 / 整洁白大褂医生服 …

`costumes.py:378 _merge_base()` 只在**相邻集且 stage_name 字符串完全相等**时合并。
语义同一件、字面永不相等 → 合并率≈0。且被「候选人正装」这类隔开后，
即使后面又叫回「医生白大褂」也**不相邻**，照样不合并——同一件白大褂
分裂成 21 个阶段各自出图，每集一个样子。

## 方案

1. **主体词提取**（非 LLM 语义——182 阶段调太贵）：从 stage_name 提取核心服装类别
   （白大褂/西装/夹克/毛衣/…）作为归一键，修饰词（笔挺/整洁/标准）统一剥掉。
2. **变体保留**：stage_name 含显式状态变化（湿透/沾血/破损）的是剧情要求的真变体，
   不能合并。只合并"同一基准状态的重复描写"。
3. **跨集合并**：同一角色、同一归一键的所有阶段（无论是否相邻）合并为一个
   大阶段 + 多个镜号区间（未来支持，现在先把名字统一）。

## 本次范围

先做 **1 归一键映射 + 2 变体识别**，输出"这 N 个阶段应该共用一个名字"的分组，
供 `costumes.py:_merge_base()` 调用。3（跨集合并的区间表示）留待后续——
那需要改 AssetStage 表结构（单行单区间 → 单行多区间 JSON），超出本轮修复范围。

归一后 21 个白大褂阶段会统一改成同一个 base_key（如 `白大褂`），
`_merge_base` 再按这个 key 合并时就能认出它们是同一件，自动合成连续段。
"""
from __future__ import annotations

import re

#: 主体词列表——按优先级排（越具体的越靠前，避免"休闲西装"先匹配到"休闲"）
_CORE_KEYWORDS = [
    "白大褂", "西装", "夹克", "衬衫", "毛衣", "羽绒服", "针织衫", "T恤",
    "便服", "正装", "工装", "休闲装", "睡衣", "病号服", "婚纱", "礼服",
    "外套", "大衣", "风衣", "卫衣", "马甲", "背心", "裙子", "连衣裙",
    "短裤", "长裤", "西裤", "牛仔裤", "运动服", "泳装", "浴袍",
    # ↓ 2026-09-01 补：以下类别整个缺失，导致大量造型名一个词都匹配不上、
    #   退回原名 → 每集一个 key → 每集一张图 = 角色无故换装。
    #   实测项目「9125」林母 ep1「贵妇套装」/ ep2「小香风套装」就是这么分裂的
    #   （剧本里对林母**没有任何**服装描写）。全库排查：85 个角色有多段基础造型，
    #   其中 33 个每段 key 都不同，如白薇「职场优雅套裙 / 嚣张助理套裙 /
    #   名牌高订包臀裙 / 时尚名媛连衣裙」——都是同一件职业裙的不同形容词。
    #   **必须追加在末尾**：上面的具体词优先级更高（"西装套装"要归到"西装"）。
    "套裙", "包臀裙", "长裙", "短裙", "半身裙", "旗袍", "汉服", "校服",
    "制服", "警服", "军装", "戏服", "套装", "长衫", "唐装", "西服",
    "衬衣", "裤装", "工作服", "运动装", "居家服", "职业装",
]

#: 变体标记——stage_name 含这些词的是剧情要求的真变体，不能与常规造型合并
_VARIANT_MARKS = [
    "湿透", "沾血", "凌乱", "破损", "破旧", "脏", "撕裂", "褪色",
    "染血", "血迹", "泥泞", "污渍", "烧焦", "残破", "褴褛",
]


def extract_base_key(stage_name: str) -> tuple[str, bool]:
    """从造型名提取归一键 + 是否为变体。

    返回 `(base_key, is_variant)`：
    - `base_key`：主体词（如 `"白大褂"`），未匹配到返回原名
    - `is_variant`：True = 显式变体（含"湿透""沾血"等），不可与常规造型合并

    示例：
        "医生白大褂" → ("白大褂", False)
        "笔挺白大褂" → ("白大褂", False)
        "湿透凌乱的白大褂" → ("白大褂", True)
        "候选人正装" → ("正装", False)
        "深色夹克外套" → ("夹克", False)
    """
    name = (stage_name or "").strip()
    is_var = any(m in name for m in _VARIANT_MARKS)
    for kw in _CORE_KEYWORDS:
        if kw in name:
            return (kw, is_var)
    # 未匹配到主体词 → 保持原名（不归一）
    return (name, is_var)


def normalize_stage_names(stages: list[dict]) -> list[dict]:
    """为一批阶段添加 `base_key` 与 `is_variant` 字段（原地修改并返回）。

    输入格式（与 `costumes.py:_merge_base` 产出一致）：
        [{"character", "stage_name", "description", "ep_from", "ep_to"}, ...]

    输出在每个 dict 里追加：
        "base_key": 归一后的主体词
        "is_variant": 是否为显式变体

    `costumes.py:_merge_base` 改为按 `(character, base_key, is_variant)` 三元组
    判断是否合并，而不是只看 `stage_name` 字符串相等。
    """
    for s in stages:
        key, var = extract_base_key(s.get("stage_name", ""))
        s["base_key"] = key
        s["is_variant"] = var
    return stages
